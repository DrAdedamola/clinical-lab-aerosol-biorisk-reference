#!/usr/bin/env python3
"""
03_qa.py - quality checks

PLAIN LANGUAGE HEADER
This script tries to break the results. It checks that every score is a whole
number in range, that every citation points at a real source, that every ISO
clause exists, that the arithmetic in the output tables matches the arithmetic
in this file computed a second, independent way, and that nothing has been
quietly imputed. It writes data/processed/qa_report.txt. Read that file before
you trust any number in this project. You do not need to read this script.
"""
import csv, json, re
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
L, FAIL = [], 0

def say(s=""):
    L.append(s); print(s)

def check(name, ok, detail=""):
    global FAIL
    say(f"  [{'PASS' if ok else 'FAIL'}] {name}{(' - ' + detail) if detail else ''}")
    if not ok:
        FAIL += 1
    return ok

def load(p):
    return yaml.safe_load(open(ROOT / p))

INSTR = load("instrument/instrument_v1.yaml")
STEPS = load("data/raw/steps.yaml")["steps"]
PROF = load("data/raw/agent_profiles.yaml")["profiles"]
SRC = load("evidence/sources.yaml")
SOURCES, PENDING = SRC["sources"], SRC["pending_verification"]
CLAUSES = {r["clause"] for r in csv.DictReader(open(ROOT / "instrument/iso35001_clauses.csv"))}
SCORES = list(csv.DictReader(open(ROOT / "data/processed/reference_scores.csv")))
EV = list(csv.DictReader(open(ROOT / "data/processed/evidence_table.csv")))
STATS = json.load(open(ROOT / "report/stats.json"))

say("=" * 78)
say("QA REPORT - Clinical Laboratory Aerosol Biorisk Reference")
say("Status: RELEASED v1.1. Generated by code/03_qa.py")
say("=" * 78)

say("\n1. COUNTS AT EACH STAGE")
say(f"  steps defined in data/raw/steps.yaml ........ {len(STEPS)}")
say(f"  agent profiles .............................. {len(PROF)}")
say(f"  scored rows (step x applicable profile) ..... {len(SCORES)}")
say(f"  instrument items ............................ {STATS['n_instrument_items']}")
say(f"  provisional sub-scores requiring a ruling ... "
    f"{sum(len(s['iars']) + len(s['crs_baseline']) + len(s['crs_recommended']) for s in STEPS.values()) + sum(3 for _ in PROF)}")
say(f"  control recommendations ..................... {STATS['n_controls']}")
say(f"  cited evidence findings ..................... {len(EV)}")
say(f"  sources in register ......................... {len(SOURCES)}")
say(f"  sources pending verification (not citable) .. {len(PENDING)}")

say("\n2. RANGE AND TYPE CHECKS ON EVERY SUB-SCORE")
bad = []
for sid, s in STEPS.items():
    for block in ("iars", "crs_baseline", "crs_recommended"):
        for k, v in s[block].items():
            if not (isinstance(v, int) and 1 <= v <= 5):
                bad.append(f"{sid}.{block}.{k}={v!r}")
for pid, p in PROF.items():
    for k in ("B1", "B2", "B3"):
        if not (isinstance(p[k], int) and 1 <= p[k] <= 5):
            bad.append(f"{pid}.{k}={p[k]!r}")
check("every sub-score is a whole number from 1 to 5", not bad, "; ".join(bad))

say("\n3. NO IMPUTATION")
check("every step scored all 5 release items (no NA, none imputed)",
      all(r["IARS_items_scored"] == "5" for r in SCORES))

say("\n4. ARITHMETIC RECOMPUTED INDEPENDENTLY")
credit = INSTR["composition"]["residual_biorisk_index"]["control_credit"]
REV = set(INSTR["dimension_A"].get("reverse_coded_items", []))
say(f"  reverse-coded release items, read from the instrument: "
    f"{sorted(REV) if REV else 'none'}")
check("the instrument declares A2 reverse-coded", "A2" in REV,
      "A2 is anchored on containment; without the reversal, better containment would "
      "raise the release score")
check("A2 carries an explicit direction note", 
      bool(INSTR["dimension_A"]["items"]["A2"].get("direction_note")),
      "the missing direction note is what allowed the original defect through")
errs = []
for r in SCORES:
    s = STEPS[r["step_id"]]
    iars = sum((6 - v) if k in REV else v for k, v in s["iars"].items()) / 5
    scs = sum(PROF[r["agent_profile"]][k] for k in ("B1", "B2", "B3")) / 3
    for state, key in (("baseline", "RBI_baseline"), ("recommended", "RBI_recommended")):
        crs = sum(s[f"crs_{state}"].values()) / 4
        want = round(max(1.0, iars - credit * (crs - 1)) * scs, 2)
        if abs(want - float(r[key])) > 0.005:
            errs.append(f"{r['step_id']}/{r['agent_profile']}/{state}: {r[key]} vs {want}")
check("every RBI in the output table reproduces from the raw sub-scores", not errs,
      "; ".join(errs))
check("every RBI is inside the 1 to 25 range",
      all(1.0 <= float(r["RBI_baseline"]) <= 25.0 and 1.0 <= float(r["RBI_recommended"]) <= 25.0
          for r in SCORES))
check("the recommended control set never scores worse than baseline",
      all(float(r["RBI_recommended"]) <= float(r["RBI_baseline"]) for r in SCORES))

say("\n5. REFERENTIAL INTEGRITY")
missing_cl = {c for s in STEPS.values() for c in s["iso35001_clauses"] if c not in CLAUSES}
check("every ISO 35001 clause cited by a step exists in the clause index",
      not missing_cl, str(missing_cl))
missing_src = {k for s in STEPS.values() for k in s["evidence_refs"] if k not in SOURCES}
check("every evidence_ref resolves to a source in the register", not missing_src,
      str(missing_src))
notcit = [r["step_id"] for r in EV if r["source_title"] == "PENDING VERIFICATION - NOT CITABLE"]
check("no finding in the evidence table cites an unverified source", not notcit,
      str(notcit) if notcit else
      f"{len(PENDING)} source(s) held in the pending register, cited nowhere")
say(f"  pending register (identified, read at second hand, deliberately NOT cited):")
for k in PENDING:
    say(f"    - {k}")
nourl = [k for k, v in SOURCES.items() if not (v.get("url") or v.get("url_contents_page"))]
check("every source record carries a URL field (not tested for reachability here)",
      not nourl, str(nourl))
say("  NOTE: reachability is tested by code/01_provenance.py --fetch, which records an "
    "HTTP fingerprint per source. See data/raw/PROVENANCE.txt.")
noauth = [k for k, v in SOURCES.items()
          if not (v.get("authors") or v.get("issuer"))]
check("every source names an author or an issuing body", not noauth, str(noauth))
nodate = [k for k, v in SOURCES.items() if not v.get("access_date")]
check("every source has an access date", not nodate, str(nodate))

say("\n6. PROFILE APPLICABILITY")
badp = [sid for sid, s in STEPS.items() if s["primary_profile"] not in s["applicable_profiles"]]
check("each step's primary profile is one of its applicable profiles", not badp, str(badp))

say("\n7. EVIDENCE GRADE DISCIPLINE")
check("evidence grade is never used as an input to any score",
      "evidence_grade" not in str(INSTR["composition"]),
      "confirmed: the composition block contains no reference to evidence grade")
ungraded = [sid for sid, s in STEPS.items()
            if s["evidence_grade"] not in INSTR["evidence_grade"]["levels"]]
check("every step carries a defined evidence grade", not ungraded, str(ungraded))
weak = [sid for sid, s in STEPS.items() if s["evidence_grade"] in ("E4", "E5")]
say(f"  NOTE: {len(weak)} step(s) rest on guidance or on nothing: {weak}")

say("\n8. NAMED SPOT CHECKS FOR THE AUTHOR")
say("  Each of these can be confirmed by hand against the source. See docs/VERIFY_CHECKLIST.md.")
spots = [
    ("S07 open culture work carries the highest baseline score in the reference",
     f"RBI_baseline = {STATS['primary_profile_rows']['S07']['RBI_baseline']} "
     f"({STATS['primary_profile_rows']['S07']['band_baseline']})"),
    ("S04 automated analysers is graded E5, no evidence located",
     f"grade = {STEPS['S04']['evidence_grade']}, research_priority = {STEPS['S04'].get('research_priority')}"),
    ("S02 centrifugation is graded E1 but flagged failure-conditional",
     f"grade = {STEPS['S02']['evidence_grade']}, conditionality = {STEPS['S02']['conditionality']}"),
    ("P3 consequence score is the mean of 5, 4 and 5",
     f"SCS(P3) = {STATS['profile_scs']['P3']}"),
    ("CLIA non-waived certificates = compliance + accreditation",
     f"{STATS['clia_denominator']['certificate_of_compliance']} + "
     f"{STATS['clia_denominator']['certificate_of_accreditation']} = "
     f"{STATS['clia_denominator']['non_waived_certificates']}"),
    ("the control credit used in every RBI is the one declared in the instrument",
     f"credit = {credit} (instrument) = {STATS['control_credit']} (stats.json)"),
]
for i, (what, val) in enumerate(spots, 1):
    say(f"  SC{i}. {what}\n        -> {val}")

say("\n9. HAND-WRITTEN DOCUMENTS CHECKED AGAINST stats.json")
say("  Generated documents interpolate from stats.json and cannot drift. Hand-written")
say("  ones can. This scans them for figures that stats.json contradicts.")
HAND = ["README.md", "docs/START_HERE.md", "docs/VERIFY_CHECKLIST.md", "docs/CODEBOOK.md",
        "docs/LIMITATIONS.md", "docs/TALK_TRACK.md", "docs/NEXT_STEPS.md",
        "docs/BUILD_SPEC.md"]
# RELEASE_NOTES.md is a changelog: it states superseded figures on purpose, so scanning
# it for agreement with the current build would flag its whole reason for existing. It is
# checked instead for the weaker property that every CURRENT figure it quotes is right,
# by scanning only lines that do not announce a change.
CHANGELOG = "RELEASE_NOTES.md"
CHANGE_WORDS = re.compile(r"\b(was|were|previously|moved from|from E[1-5]|"
                          r"corrected|struck|pulled|replaced|rebuilt|unchanged)\b", re.I)
# claim -> the stats.json value it must agree with
LIVE = {
    "n_steps": STATS["n_steps"],
    "n_controls": STATS["n_controls"],
    "n_sources": STATS["n_sources"],
    "n_evidence_findings": STATS["n_evidence_findings"],
    "n_scored_rows": STATS["n_scored_rows"],
    "n_instrument_items": STATS["n_instrument_items"],
}
# A line naming a step may legitimately quote any of that step's published figures,
# not only its baseline index: a worked example cites sub-score means, a rationale
# cites IARS. The check therefore holds every value the step legitimately has and
# flags a decimal only when it matches none of them.
LIVE_BY_STEP = {}
for sid, r in STATS["primary_profile_rows"].items():
    row = next(x for x in SCORES
               if x["step_id"] == sid and x["agent_profile"] == r["profile"])
    allowed = {float(row[k]) for k in
               ("IARS", "SCS", "CRS_baseline", "CRS_recommended",
                "residual_release_baseline", "residual_release_recommended",
                "RBI_baseline", "RBI_recommended", "RBI_reduction")}
    allowed |= {round(v, 1) for v in list(allowed)}
    LIVE_BY_STEP[sid] = (allowed, r["RBI_baseline"], r["evidence_grade"])
stale = []
for rel in HAND + [CHANGELOG]:
    f = ROOT / rel
    if not f.exists():
        continue
    text = f.read_text()
    for line_no, line in enumerate(text.splitlines(), 1):
        if rel == CHANGELOG and CHANGE_WORDS.search(line):
            continue            # a line describing what changed may quote old figures
        named = [sid for sid in LIVE_BY_STEP if sid in line]
        # a line may compare several steps, so pool every named step's figures
        pooled = set().union(*(LIVE_BY_STEP[s][0] for s in named)) if named else set()
        for sid in named:
            allowed, rbi, grade = LIVE_BY_STEP[sid]
            allowed = pooled
            for tok in re.findall(r"\b\d{1,2}\.\d{1,2}\b", line):
                v = float(tok)
                if not (1.0 <= v <= 25.0):
                    continue
                if not any(abs(v - a) < 0.005 for a in allowed):
                    stale.append(f"{rel}:{line_no} mentions {sid} with {tok}, which is "
                                 f"none of that step's published figures "
                                 f"(baseline index {rbi})")
            for g in re.findall(r"\bE[1-5]\b", line):
                if g != grade:
                    stale.append(f"{rel}:{line_no} mentions {sid} with {g}; "
                                 f"stats.json says {grade}")
check("no hand-written document contradicts stats.json on a step index or grade",
      not stale, "; ".join(stale[:6]) + (" ..." if len(stale) > 6 else ""))
say(f"  scanned {len(HAND)} hand-written document(s) against "
    f"{len(LIVE_BY_STEP)} step indices and grades")

say("\n10. RELEASE DISCIPLINE")
nv = sum(1 for s in STEPS.values() for v in str(s).split() if "[VERIFY-" in v)
check("no unresolved VERIFY tags remain in the step files", nv == 0,
      f"{nv} tag(s) still present" if nv else "")
check("no unresolved VERIFY tags remain in the instrument",
      "[VERIFY-" not in str(INSTR))
check("stats.json is marked RELEASED", STATS["status"] == "RELEASED")
check("every finding in the evidence table resolves to a verified source",
      all(r["source_title"] != "PENDING VERIFICATION - NOT CITABLE" for r in EV))

say("\n" + "=" * 78)
say(f"RESULT: {FAIL} failed check(s)." if FAIL else "RESULT: all checks passed.")
say("This report confirms the arithmetic and the referencing are sound.")
say("It does NOT confirm that any score is correct. Only the author can do that.")
say("=" * 78)

out = ROOT / "data/processed/qa_report.txt"
out.write_text("\n".join(L) + "\n")
print(f"\nwritten to {out}")
raise SystemExit(1 if FAIL else 0)
